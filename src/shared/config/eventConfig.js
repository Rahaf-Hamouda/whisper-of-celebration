export function formatEventDate({ day = 'numeric', month = 'long', year = 'numeric' } = {}) {
  return new Intl.DateTimeFormat('ar-SY', {
    day,
    month,
    year,
    timeZone: eventConfig.occasion.timeZone,
  }).format(new Date(eventConfig.occasion.date));
}
